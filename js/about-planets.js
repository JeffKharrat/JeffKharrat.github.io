  if (a.x >= a.y && a.x >= a.z) { if (p.x > 0.) { D = vec3(1.,0.,0.); U = vec3(0.,0.,-1.); } else { D = vec3(-1.,0.,0.); U = vec3(0.,0.,1.); } V = vec3(0.,1.,0.); }
